-- Reversible post trash history. Posts retain their rows and every related
-- record; deleted_at remains the single visibility switch used by readers.
CREATE TABLE IF NOT EXISTS post_trash_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts (id),
    action TEXT NOT NULL CHECK (action IN ('trash', 'restore')),
    actor TEXT NOT NULL CHECK (length(btrim(actor)) BETWEEN 1 AND 120),
    reason TEXT NOT NULL DEFAULT '' CHECK (length(reason) <= 512),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS post_trash_actions_post_created_idx
    ON post_trash_actions (post_id, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS posts_trash_created_idx
    ON posts (deleted_at DESC, id DESC)
    WHERE deleted_at IS NOT NULL;
