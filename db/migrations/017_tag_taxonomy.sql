-- Bounded tag rename/merge taxonomy.
-- Idempotent: safe to re-run; lexical runner picks this up after 016.
-- posts.tags TEXT[] remains the current-tag store; history stays in
-- post_tag_revisions. tag_redirects holds flattened retired->canonical
-- aliases (canonical is always a current tag, never another retired tag).

CREATE TABLE IF NOT EXISTS tag_taxonomy_state (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);

INSERT INTO tag_taxonomy_state (id, version) VALUES (1, 0)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS tag_redirects (
    retired_tag TEXT PRIMARY KEY,
    canonical_tag TEXT NOT NULL,
    CHECK (retired_tag <> canonical_tag)
);

CREATE TABLE IF NOT EXISTS tag_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode TEXT NOT NULL CHECK (mode IN ('rename', 'merge')),
    source_tag TEXT NOT NULL,
    target_tag TEXT NOT NULL,
    version BIGINT NOT NULL UNIQUE CHECK (version > 0),
    affected_post_count BIGINT NOT NULL CHECK (affected_post_count >= 0),
    visible_post_count BIGINT NOT NULL CHECK (visible_post_count >= 0),
    actor TEXT NOT NULL CHECK (length(btrim(actor)) BETWEEN 1 AND 120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (source_tag <> target_tag)
);

CREATE INDEX IF NOT EXISTS tag_redirects_canonical_idx
    ON tag_redirects (canonical_tag);

CREATE INDEX IF NOT EXISTS tag_operations_created_idx
    ON tag_operations (created_at DESC, id DESC);

ALTER TABLE post_tag_revisions
    ADD COLUMN IF NOT EXISTS tag_operation_id BIGINT REFERENCES tag_operations(id);

CREATE INDEX IF NOT EXISTS posts_tags_gin ON posts USING GIN (tags);
