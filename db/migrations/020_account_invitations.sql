-- Single-use account invitations. Raw invitation tokens are never stored.
-- Additive and safe to apply repeatedly.
CREATE TABLE IF NOT EXISTS account_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE CHECK (length(token_hash) = 64),
    role TEXT NOT NULL CHECK (role IN ('viewer', 'editor', 'admin')),
    issuer_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    issuer_actor_id TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ,
    CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS account_invitations_active_idx
    ON account_invitations (expires_at, id)
    WHERE revoked_at IS NULL AND used_at IS NULL;
